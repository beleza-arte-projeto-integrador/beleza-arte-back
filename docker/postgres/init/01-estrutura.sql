-- =====================================================================
-- 01 - Estrutura do banco Beleza & Arte (banco LOCAL de testes, Docker)
--
-- Mesma estrutura do Supabase (veja docs/banco-de-dados.md).
-- Roda sozinho só na PRIMEIRA vez que o container sobe com o volume vazio.
-- Mudou algo aqui? Recrie o banco: docker compose down -v && docker compose up -d --build
--
-- Origem: script V1 do Flyway (removido no commit ebff0d6), com a tabela
-- clients já sem address, birth_date, preferences e updated_at.
-- =====================================================================


-- ---------------------------------------------------------------------
-- PROFISSIONAIS: quem trabalha no salao (e faz login no sistema)
-- ---------------------------------------------------------------------
CREATE TABLE professionals (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(120) NOT NULL,
    cpf              CHAR(11)     UNIQUE,
    email            VARCHAR(160) UNIQUE,
    phone            VARCHAR(20),
    specialty        VARCHAR(80),
    experience_years INTEGER      CHECK (experience_years >= 0),
    username         VARCHAR(50)  UNIQUE,
    password_hash    VARCHAR(255),
    role             VARCHAR(20)  NOT NULL DEFAULT 'PROFESSIONAL'
                     CHECK (role IN ('ADMIN', 'PROFESSIONAL')),
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ
);


-- ---------------------------------------------------------------------
-- CLIENTES: quem agenda os servicos
-- ---------------------------------------------------------------------
CREATE TABLE clients (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    phone       VARCHAR(20)  NOT NULL UNIQUE,
    email       VARCHAR(160),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);


-- ---------------------------------------------------------------------
-- SERVICOS: o que o salao oferece (corte, manicure, mechas...)
-- ---------------------------------------------------------------------
CREATE TABLE services (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100)  NOT NULL UNIQUE,
    description      TEXT,
    category         VARCHAR(50),
    duration_minutes INTEGER       NOT NULL CHECK (duration_minutes > 0),
    price            NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    active           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);


-- ---------------------------------------------------------------------
-- PROFISSIONAL x SERVICO: quais servicos cada profissional sabe fazer
-- (relacao "muitos para muitos")
-- ---------------------------------------------------------------------
CREATE TABLE professional_services (
    professional_id INTEGER NOT NULL REFERENCES professionals (id) ON DELETE CASCADE,
    service_id      INTEGER NOT NULL REFERENCES services (id)      ON DELETE CASCADE,
    PRIMARY KEY (professional_id, service_id)
);


-- ---------------------------------------------------------------------
-- DISPONIBILIDADE: horario de trabalho de cada profissional na semana
-- ---------------------------------------------------------------------
CREATE TABLE professional_availability (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professional_id INTEGER  NOT NULL REFERENCES professionals (id) ON DELETE CASCADE,
    weekday         SMALLINT NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    start_time      TIME     NOT NULL,
    end_time        TIME     NOT NULL,
    CHECK (end_time > start_time),
    UNIQUE (professional_id, weekday, start_time)
);


-- ---------------------------------------------------------------------
-- RECURSOS: cadeiras, cabines e equipamentos do salao
-- ---------------------------------------------------------------------
CREATE TABLE resources (
    id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(80) NOT NULL,
    type   VARCHAR(20) NOT NULL CHECK (type IN ('CADEIRA', 'CABINE', 'EQUIPAMENTO')),
    active BOOLEAN     NOT NULL DEFAULT TRUE
);


-- ---------------------------------------------------------------------
-- AGENDAMENTOS: a "visita" do cliente (pode ter varios servicos)
-- ---------------------------------------------------------------------
CREATE TABLE appointments (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id     INTEGER     NOT NULL REFERENCES clients (id),
    status        VARCHAR(20) NOT NULL DEFAULT 'AGENDADO'
                  CHECK (status IN ('AGENDADO', 'CONFIRMADO', 'CONCLUIDO', 'CANCELADO', 'NAO_COMPARECEU')),
    notes         TEXT,
    cancelled_by  VARCHAR(10) CHECK (cancelled_by IN ('CLIENTE', 'SALAO')),
    cancel_reason VARCHAR(255),
    cancelled_at  TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ
);

CREATE INDEX idx_appointments_client ON appointments (client_id);


-- ---------------------------------------------------------------------
-- ITENS DO AGENDAMENTO: cada servico da visita, com profissional e horario
-- ---------------------------------------------------------------------
CREATE TABLE appointment_items (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id  INTEGER       NOT NULL REFERENCES appointments (id) ON DELETE CASCADE,
    service_id      INTEGER       NOT NULL REFERENCES services (id),
    professional_id INTEGER       NOT NULL REFERENCES professionals (id),
    resource_id     INTEGER       REFERENCES resources (id),
    start_at        TIMESTAMPTZ   NOT NULL,
    end_at          TIMESTAMPTZ   NOT NULL,
    price           NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    CHECK (end_at > start_at)
);

-- Indices para a busca mais comum: "a agenda do profissional X no dia Y"
CREATE INDEX idx_items_professional_start ON appointment_items (professional_id, start_at);
CREATE INDEX idx_items_resource_start     ON appointment_items (resource_id, start_at);
CREATE INDEX idx_items_appointment        ON appointment_items (appointment_id);


-- ---------------------------------------------------------------------
-- PAGAMENTOS: valores pagos por agendamento
-- ---------------------------------------------------------------------
CREATE TABLE payments (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER       NOT NULL REFERENCES appointments (id),
    amount         NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    method         VARCHAR(20)   NOT NULL
                   CHECK (method IN ('PIX', 'CARTAO_CREDITO', 'CARTAO_DEBITO', 'DINHEIRO')),
    status         VARCHAR(20)   NOT NULL DEFAULT 'PENDENTE'
                   CHECK (status IN ('PENDENTE', 'PAGO', 'CANCELADO', 'ESTORNADO')),
    paid_at        TIMESTAMPTZ,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_payments_appointment ON payments (appointment_id);
CREATE INDEX idx_payments_status_paid ON payments (status, paid_at);
